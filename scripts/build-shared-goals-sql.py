"""Build the standalone SQL-editor test; --check never edits files."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = ROOT / "supabase/migrations/20261024160000_shared_goals.sql"
ASSERTIONS = ROOT / "supabase/tests/shared_goals.assertions.sql"
OUTPUT = ROOT / "supabase/tests/shared_goals.sql"
HEADER = """-- LOCAL/FRESH DISPOSABLE SUPABASE ONLY. Never run against live data.
-- Self-contained SQL-editor test: migration + real-role assertions + rerun.
-- Requires existing auth.users/auth.uid(), anon/authenticated (Supabase).
-- Refuses existing planner/shared tables. Everything rolls back at the end.
-- An error aborts the transaction: ROLLBACK before retrying.
-- Generated by scripts/build-shared-goals-sql.py; edit assertions/migration.
begin;
do $$ begin
  if to_regclass('public.shared_groups') is not null
    or to_regclass('public.shared_profiles') is not null
    or to_regclass('public.goals') is not null or to_regclass('public.events') is not null
    or to_regclass('public.notes') is not null or to_regclass('public.diary_entries') is not null then
    raise exception 'Use a fresh disposable database with no planner/shared tables';
  end if;
  if to_regclass('auth.users') is null or to_regprocedure('auth.uid()') is null then
    raise exception 'Supabase auth prerequisites required (or explicit disposable test scaffold)';
  end if;
end $$;
"""

def generated():
    body = re.sub(r"^(?:begin|commit);[ \t]*\n?", "", MIGRATION.read_text(encoding="utf-8"), flags=re.M).strip()
    return (HEADER + "\n-- BEGIN shared migration\n" + body + "\n-- END shared migration\n\n"
            + ASSERTIONS.read_text(encoding="utf-8").rstrip() + "\n\n"
            + "-- BEGIN shared migration rerun\n" + body + "\n-- END shared migration rerun\n"
            + "select pg_temp.check_true((select count(*) from public.shared_checkins)=current_setting('shared_test.checkins')::int,'rerun preserves check-ins');\n"
            + "select pg_temp.check_true((select count(*) from public.shared_memberships)=current_setting('shared_test.memberships')::int,'rerun preserves membership epochs');\n"
            + "select pg_temp.check_true((select count(*) from facta_private.shared_command_receipts)=current_setting('shared_test.receipts')::int,'rerun preserves receipts');\n"
            + "select pg_temp.set_clock('2026-11-16 10:00+03');\n"
            + "select pg_temp.check_true((select count(*) from public.shared_goal_round_scores where group_id=(select (v->>'group_id')::uuid from sg_fixture where k='lifecycle'))=4,'rerun preserves archived scored-round set');\n"
            + "select 'shared_goals: all SQL assertions passed ('||n||' checked assertions, plus exception assertions)' as result from sg_assertions;\nrollback;\n")

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("shared_goals.sql is stale; run scripts/build-shared-goals-sql.py")
        print("shared_goals.sql is synchronized")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
